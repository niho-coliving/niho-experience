import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { copyFile, mkdtemp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

const packageDir = resolve(fileURLToPath(new URL("..", import.meta.url)));
const repoDir = resolve(packageDir, "../..");
const sourceDir = resolve(packageDir, "src/v1");
const distDir = resolve(packageDir, "dist/v1");
const check = process.argv.includes("--check");
const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const stable = (value) => `${JSON.stringify(value, null, 2)}\n`;

const copyRegistry = JSON.parse(await readFile(resolve(sourceDir, "copy-registry.json"), "utf8"));
const staticCopyAdditions = JSON.parse(await readFile(resolve(sourceDir, "static-copy-additions.json"), "utf8"));
const assetSource = JSON.parse(await readFile(resolve(sourceDir, "assets.source.json"), "utf8"));
if (copyRegistry.schemaVersion !== 1 || Object.keys(copyRegistry.definitions).length !== 239) throw new Error("v1 copy registry must contain the canonical 239 keys");
if (staticCopyAdditions.schemaVersion !== 2 || staticCopyAdditions.legacySchemaVersion !== 1) throw new Error("v1 static copy additions must extend schema 1 as schema 2");
for (const key of Object.keys(staticCopyAdditions.definitions)) if (key in copyRegistry.definitions) throw new Error(`Duplicate static copy key: ${key}`);
const staticCopyRegistry = {
  schemaVersion: 2,
  legacySchemaVersion: 1,
  definitions: { ...copyRegistry.definitions, ...staticCopyAdditions.definitions },
};

const assetDigests = {};
for (const [id, asset] of Object.entries(assetSource.assets)) {
  const file = await readFile(resolve(repoDir, "apps/web/public", asset.src.slice(1)));
  assetDigests[id] = { src: sha256(file) };
  if (asset.kind === "video") assetDigests[id].poster = sha256(await readFile(resolve(repoDir, "apps/web/public", asset.poster.slice(1))));
}
const fontFiles = [
  ["nunito", "nunito-latin-wght-normal.woff2"], ["nunito", "nunito-latin-ext-wght-normal.woff2"],
  ["fraunces", "fraunces-latin-wght-normal.woff2"], ["fraunces", "fraunces-latin-ext-wght-normal.woff2"],
  ["caveat", "caveat-latin-wght-normal.woff2"], ["caveat", "caveat-latin-ext-wght-normal.woff2"],
];
const fontPackages = { nunito: "@fontsource-variable/nunito", fraunces: "@fontsource-variable/fraunces", caveat: "@fontsource-variable/caveat" };
const fontDigests = {};
for (const [family, file] of fontFiles) fontDigests[file] = sha256(await readFile(resolve(repoDir, "node_modules", fontPackages[family], "files", file)));

const cssSource = await readFile(resolve(sourceDir, "styles.source.css"), "utf8");
const compiled = await postcss([tailwind()]).process(cssSource, { from: resolve(sourceDir, "styles.source.css") });
const cssRoot = postcss.parse(compiled.css);
cssRoot.walkRules((rule) => {
  if (rule.selector === ":root, :host" || rule.selector === "html" || rule.selector === "body") rule.selector = ":scope";
});
for (const node of [...cssRoot.nodes]) {
  if (node.type === "comment" || (node.type === "atrule" && (!node.nodes || node.name === "property" || node.name === "font-face" || node.name.endsWith("keyframes")))) continue;
  if (node.type === "atrule" && node.nodes) {
    const scope = postcss.atRule({ name: "scope", params: "(.nexp-v1)" });
    scope.append(...node.nodes.map((child) => child.clone()));
    node.removeAll();
    node.append(scope);
  } else if (node.type === "rule") {
    const scope = postcss.atRule({ name: "scope", params: "(.nexp-v1)" });
    scope.append(node.clone());
    node.replaceWith(scope);
  }
}
const scopedCss = cssRoot.toString();
const generated = `/* Generated by scripts/build.mjs. Do not edit. */\n` +
  `export const GENERATED_STYLE_SHA256_V1 = ${JSON.stringify(sha256(scopedCss))};\n` +
  `export const GENERATED_ASSET_REGISTRY_SHA256_V1 = ${JSON.stringify(sha256(stable(assetSource)))};\n` +
  `export const GENERATED_COPY_REGISTRY_SHA256_V1 = ${JSON.stringify(sha256(stable(copyRegistry)))};\n` +
  `export const GENERATED_STATIC_COPY_REGISTRY_SHA256_V1 = ${JSON.stringify(sha256(stable(staticCopyRegistry)))};\n` +
  `export const GENERATED_FONT_DIGESTS_V1 = ${JSON.stringify(fontDigests, null, 2)} as const;\n` +
  `export const GENERATED_ASSET_DIGESTS_V1 = ${JSON.stringify(assetDigests, null, 2)} as const;\n` +
  `export const COPY_REGISTRY_GENERATED_V1 = ${JSON.stringify(copyRegistry, null, 2)} as const;\n` +
  `export const STATIC_COPY_REGISTRY_GENERATED_V1 = ${JSON.stringify(staticCopyRegistry, null, 2)} as const;\n` +
  `export const ASSET_SOURCE_GENERATED_V1 = ${JSON.stringify(assetSource, null, 2)} as const;\n`;

async function writeOrCheck(path, content) {
  if (check) {
    const current = await readFile(path, "utf8").catch(() => "");
    if (current !== content) throw new Error(`Generated file is stale: ${path}`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
}

async function filesUnder(directory, prefix = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...await filesUnder(resolve(directory, entry.name), relative));
    else if (entry.isFile()) files.push(relative);
  }
  return files.sort();
}

await writeOrCheck(resolve(sourceDir, "generated.ts"), generated);
if (check) {
  const temporary = await mkdtemp(resolve(tmpdir(), "niho-presentation-v1-"));
  try {
    execFileSync(resolve(repoDir, "node_modules/.bin/tsc"), ["-p", resolve(packageDir, "tsconfig.json"), "--outDir", temporary], { cwd: repoDir, stdio: "pipe" });
    const compiledFiles = await filesUnder(temporary);
    const expectedFiles = [...compiledFiles, "static-copy-registry.json", "styles.css", ...fontFiles.map(([, file]) => `fonts/${file}`)].sort();
    const actualFiles = await filesUnder(distDir).catch(() => []);
    if (JSON.stringify(actualFiles) !== JSON.stringify(expectedFiles)) throw new Error("Generated distribution file set is stale");
    for (const name of compiledFiles) {
      const expected = await readFile(resolve(temporary, name));
      const actual = await readFile(resolve(distDir, name));
      if (!expected.equals(actual)) throw new Error(`Generated distribution is stale: ${name}`);
    }
    if (await readFile(resolve(distDir, "styles.css"), "utf8") !== scopedCss) throw new Error("Generated distribution is stale: styles.css");
    if (await readFile(resolve(distDir, "static-copy-registry.json"), "utf8") !== stable(staticCopyRegistry)) throw new Error("Generated distribution is stale: static-copy-registry.json");
    for (const [family, file] of fontFiles) {
      const expected = await readFile(resolve(repoDir, "node_modules", fontPackages[family], "files", file));
      const actual = await readFile(resolve(distDir, "fonts", file)).catch(() => Buffer.alloc(0));
      if (!expected.equals(actual)) throw new Error(`Generated font is stale: ${file}`);
    }
  } finally { await rm(temporary, { recursive: true, force: true }); }
} else {
  await rm(distDir, { recursive: true, force: true });
  execFileSync(resolve(repoDir, "node_modules/.bin/tsc"), ["-p", resolve(packageDir, "tsconfig.json")], { cwd: repoDir, stdio: "inherit" });
  await writeOrCheck(resolve(distDir, "styles.css"), scopedCss);
  await writeOrCheck(resolve(distDir, "static-copy-registry.json"), stable(staticCopyRegistry));
  await mkdir(resolve(distDir, "fonts"), { recursive: true });
  for (const [family, file] of fontFiles) await copyFile(resolve(repoDir, "node_modules", fontPackages[family], "files", file), resolve(distDir, "fonts", file));
}
